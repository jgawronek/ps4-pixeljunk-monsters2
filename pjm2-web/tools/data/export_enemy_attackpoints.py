#!/usr/bin/env python3
"""Export the per-enemy Q4.EnemyBase.AttackPoints() hierarchy (descendants named 'AttackPoint', GameObjectHelper.FindDeepList)
from the `enemies` AssetBundle: local position, SphereCollider radius, AttackPointSetting, own EnemyAttributesSettings tables.
Output: src/data/enemyAttackPoints.generated.ts.   Usage: /srv/opencode/venv-unity/bin/python -I tools/data/export_enemy_attackpoints.py"""
import json, os, UnityPy
ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..'))
AB = os.path.join(ROOT, 'game/extracted/CUSA11967/Media/StreamingAssets/AssetBundles')
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'src', 'data', 'enemyAttackPoints.generated.ts')
env = UnityPy.load(os.path.join(AB, 'enemies'))
objs = {o.path_id: o for o in env.objects}
tt = {}
def T(p):
    if p not in tt: tt[p] = objs[p].read_typetree()
    return tt[p]
def comps(g): return [(objs[c['component']['m_PathID']].type.name, c['component']['m_PathID']) for c in T(g)['m_Component']]
def script_class(m):
    s = T(m)['m_Script']['m_PathID']
    return T(s).get('m_ClassName') if s in objs else None
def tf_of(g):
    for n, p in comps(g):
        if n in ('Transform', 'RectTransform'): return p
res = {}
for pid, o in objs.items():
    if o.type.name != 'GameObject': continue
    cs = comps(pid)
    if not any(n == 'MonoBehaviour' and script_class(p) == 'EnemyBase' for n, p in cs): continue
    name = T(pid)['m_Name']
    pts = []
    def walk(tr, depth):
        t = T(tr); g = t['m_GameObject']['m_PathID']
        if T(g)['m_Name'] == 'AttackPoint' and depth > 0:
            c = comps(g)
            sph = [T(p) for n, p in c if n == 'SphereCollider']
            aps = [T(p) for n, p in c if n == 'MonoBehaviour' and script_class(p) == 'AttackPointSetting']
            att = [T(p) for n, p in c if n == 'MonoBehaviour' and script_class(p) == 'EnemyAttributesSettings']
            lp = t['m_LocalPosition']
            pts.append({'path_depth': depth, 'pos': [lp['x'], lp['y'], lp['z']],
                        'radius': sph[0]['m_Radius'] if sph else None,
                        'moveTypeOverride': aps[0]['moveTypeOverride'] if aps else 0,
                        'afterAirPoints': int(aps[0]['afterAirPoints']) if aps else 0,
                        'attr': ({'strength': [[round(i['damageTime'], 6), round(i['reactionTime'], 6)] for i in att[0]['strengthDamageInfos']],
                                  'cls': [[round(i['damageTime'], 6), round(i['reactionTime'], 6)] for i in att[0]['classDamageInfos']]} if att else None)})
        for ch in t['m_Children']: walk(ch['m_PathID'], depth + 1)
    walk(tf_of(pid), 0)
    res[name] = pts
for n in sorted(res): print(n, len(res[n]), [(p['path_depth'], p['moveTypeOverride']) for p in res[n]][:6])
with open(OUT, 'w') as fo:
    fo.write('// GENERATED by tools/data/export_enemy_attackpoints.py (enemies AssetBundle) - do not edit.\n')
    fo.write('// Q4.EnemyBase.AttackPoints(): descendants named "AttackPoint" -> sim GameCoreEnemyAttackPoint (weak points).\n')
    fo.write('export interface AttackPointData { depth: number; pos: [number, number, number]; radius: number | null; moveTypeOverride: number; afterAirPoints: boolean; attr: { strength: number[][]; cls: number[][] } | null }\n')
    fo.write('export const ENEMY_ATTACK_POINTS: Readonly<Record<string, AttackPointData[]>> = ' + json.dumps({n: [{'depth': p['path_depth'], 'pos': p['pos'], 'radius': p['radius'], 'moveTypeOverride': p['moveTypeOverride'], 'afterAirPoints': bool(p['afterAirPoints']), 'attr': p['attr']} for p in v] for n, v in res.items() if v}, indent=1) + ';\n')
