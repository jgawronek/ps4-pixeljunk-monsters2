#!/usr/bin/env python3
"""
export_hub_trees.py — the hub's (3d_stage_000) nature trees. In the original each `tree_00N` node carries a NatureTree + a PrefabLoader whose
prefabRandomList (4 x tree_00N_k_pa, nature bundle) is instantiated at Awake (Random.Range pick) at the node's transform. The stage extractor
skips these (no renderer on the node), so the port's hub was missing ALL 65 trees (flower trees, bushes ...). This exports the active nodes with
their WORLD TRS (Unity space) to src/data/hubTrees.generated.ts. Species 001/002 reuse the stage tree GLBs; 006/007/008/010 are extracted by
tools/assets/extract_trees.py.

Usage (from pjm2-web/):  python3 tools/data/export_hub_trees.py
"""
import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
SCENE = os.path.join(ROOT, 'public/assets/stages/3d_stage_000/scene.json')
OUT = os.path.join(ROOT, 'src/data/hubTrees.generated.ts')


def qmul(a, b):
    ax, ay, az, aw = a
    bx, by, bz, bw = b
    return (aw * bx + ax * bw + ay * bz - az * by, aw * by - ax * bz + ay * bw + az * bx,
            aw * bz + ax * by - ay * bx + az * bw, aw * bw - ax * bx - ay * by - az * bz)


def qrot(q, v):
    x, y, z, w = q
    tx = 2 * (y * v[2] - z * v[1]); ty = 2 * (z * v[0] - x * v[2]); tz = 2 * (x * v[1] - y * v[0])
    return (v[0] + w * tx + y * tz - z * ty, v[1] + w * ty + z * tx - x * tz, v[2] + w * tz + x * ty - y * tx)


def main():
    s = json.load(open(SCENE))
    N = s['nodes']
    cache = {}

    def world(i):
        if i in cache:
            return cache[i]
        n = N[i]
        p = n['parent']
        lp, lr, ls = tuple(n['pos']), tuple(n['rot']), tuple(n['scale'])
        if p is None or p < 0:
            cache[i] = (lp, lr, ls)
        else:
            pp, pr, ps = world(p)
            r = qrot(pr, (lp[0] * ps[0], lp[1] * ps[1], lp[2] * ps[2]))
            cache[i] = ((pp[0] + r[0], pp[1] + r[1], pp[2] + r[2]), qmul(pr, lr), (ps[0] * ls[0], ps[1] * ls[1], ps[2] * ls[2]))
        return cache[i]

    rows = []
    for n in N:
        base = n['name'].split(' ')[0]
        if base.startswith('tree_') and n['activeInHierarchy'] and len(base) == 8:
            p, q, sc = world(n['i'])
            rows.append({'i': n['i'], 'species': base, 'pos': [round(v, 4) for v in p], 'rot': [round(v, 5) for v in q], 'scale': round(sum(sc) / 3, 4)})
    import math
    chibis = []
    for n in N:
        if n['name'].split(' ')[0] == 'chibi_01' and n['activeInHierarchy']:
            p, q, _ = world(n['i'])
            yaw = math.degrees(math.atan2(2 * (q[3] * q[1] + q[0] * q[2]), 1 - 2 * (q[1] * q[1] + q[0] * q[0])))
            chibis.append({'i': n['i'], 'pos': [round(v, 4) for v in p], 'yaw': round(yaw, 3)})
    with open(OUT, 'w') as f:
        f.write('// GENERATED by tools/data/export_hub_trees.py — DO NOT EDIT.\n')
        f.write('// Active nature-tree nodes of the hub scene (world TRS, Unity space). Species = node name prefix; variant picked per node by the view.\n')
        f.write('export interface HubTreeNode { i: number; species: string; pos: [number, number, number]; rot: [number, number, number, number]; scale: number }\n')
        f.write('export interface HubChibiNode { i: number; pos: [number, number, number]; yaw: number }\n')
        f.write('/** `chibi_01` PrefabLoader NPC chibis of the hub (chibi prefab = chibi_00 rig; MiniDialog interaction not ported). */\n')
        f.write('export const HUB_CHIBIS: readonly HubChibiNode[] = ' + json.dumps(chibis) + ' as unknown as readonly HubChibiNode[];\n')
        f.write('export const HUB_TREES: readonly HubTreeNode[] = ' + json.dumps(rows) + ' as unknown as readonly HubTreeNode[];\n')
    print('wrote', OUT, len(rows))


if __name__ == '__main__':
    main()
