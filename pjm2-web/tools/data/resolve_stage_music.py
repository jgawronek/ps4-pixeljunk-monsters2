#!/usr/bin/env python3
"""resolve_stage_music.py -- StageMain.m_stageMusic / m_bossMusic PPtr -> AudioClip names, per stage scene.

StageMain.Start @005260a0 plays m_stageMusic (+0x28) through Q4.MonstersAudio.PlayBGMusic; OnWaveActivate
@00527160 plays m_bossMusic (+0x30) when the LAST wave activates (decomp/decompiled/Q4.StageMain.c L345, L1054).
The PPtrs are cross-file refs (m_FileID = index+1 into the scene file's externals, here the *.sharedAssets
of another stage scene), so they are resolved with UnityPy from the stages bundle.
Writes src/data/stageMusic.generated.ts.
Usage: /srv/opencode/venv-unity/bin/python -I tools/data/resolve_stage_music.py
"""
import json, os
import UnityPy

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
REPO = os.path.abspath(os.path.join(ROOT, '..'))
AB = os.path.join(REPO, 'game/extracted/CUSA11967/Media/StreamingAssets/AssetBundles/stages')
idx = json.load(open(os.path.join(ROOT, 'public/assets/data/stages-index.json')))['stages']
bun = UnityPy.load(AB).files[AB]


def name_of(sf, pid):
    o = sf.objects.get(pid)
    return None if o is None else getattr(o.read(), 'm_Name', None)


rows = []
for s in idx:
    sf = bun.files[f"BuildPlayer-{s['scene']}_env"]
    out = {}
    for key in ('stageMusic', 'bossMusic'):
        ref = s[key]
        fid, pid = ref['m_FileID'], ref['m_PathID']
        if pid == 0:
            out[key] = None
        elif fid == 0:
            out[key] = name_of(sf, pid)
        else:
            base = sf.externals[fid - 1].path.split('/')[-1].lower()
            tgt = next(f for n, f in bun.files.items() if n.lower().endswith(base) and hasattr(f, 'objects'))
            out[key] = name_of(tgt, pid)
    rows.append("  '%s': { stageMusic: %s, bossMusic: %s }," % (
        s['scene'], ("'%s'" % out['stageMusic']) if out['stageMusic'] else 'null', ("'%s'" % out['bossMusic']) if out['bossMusic'] else 'null'))
    print(s['scene'], out)
open(os.path.join(ROOT, 'src/data/stageMusic.generated.ts'), 'w').write('''// GENERATED by tools/data/resolve_stage_music.py -- do not edit.
// StageMain.m_stageMusic / m_bossMusic AudioClip names per stage scene (public/assets/audio/bgm/<name>.wav).
export const STAGE_MUSIC: Readonly<Record<string, { stageMusic: string | null; bossMusic: string | null }>> = {
%s
};
''' % '\n'.join(rows))
