#!/usr/bin/env python3
"""Export the per-enemy model bounds the sim reads at spawn: GameCoreEnemy ctor -> FindTransformWithTag('Character') ->
GetComponentInChildren<Renderer>().bounds -> Cylinder.fromBounds (radius = min(ext.x,ext.z) + 0.2*(max-min), height = size.y).

Source: the extracted character GLBs (public/assets/characters/<def>/<def>.glb, produced from the enemies bundle prefabs by
tools/assets/extract_all_characters.py). The value is computed EXACTLY like the browser (CharacterLibrary.prepare): the bind-pose
AABB of every mesh node (geometry POSITION min/max through the node's world matrix; three's Box3.setFromObject), size only
(the sim reads size.y and extents.x/z; mirroring x is size-invariant).
Output: src/data/enemyBounds.generated.ts.   Usage: python3 tools/data/export_enemy_bounds.py"""
import json, os, struct, itertools
ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
CH = os.path.join(ROOT, 'public', 'assets', 'characters')
OUT = os.path.join(ROOT, 'src', 'data', 'enemyBounds.generated.ts')

def mat_mul(a, b):  # column-major 4x4
    return [sum(a[k*4+r] * b[c*4+k] for k in range(4)) for c in range(4) for r in range(4)]

def trs(n):
    if 'matrix' in n: return list(n['matrix'])
    t = n.get('translation', [0, 0, 0]); q = n.get('rotation', [0, 0, 0, 1]); s = n.get('scale', [1, 1, 1])
    x, y, z, w = q
    r = [1-2*(y*y+z*z), 2*(x*y+z*w), 2*(x*z-y*w), 0,
         2*(x*y-z*w), 1-2*(x*x+z*z), 2*(y*z+x*w), 0,
         2*(x*z+y*w), 2*(y*z-x*w), 1-2*(x*x+y*y), 0, 0, 0, 0, 1]
    for c in range(3):
        for rr in range(3): r[c*4+rr] *= s[c]
    r[12], r[13], r[14] = t
    return r

def glb_bounds(path):
    with open(path, 'rb') as f: data = f.read()
    jl = struct.unpack_from('<I', data, 12)[0]
    j = json.loads(data[20:20+jl])
    nodes = j['nodes']; parent = {}
    for i, n in enumerate(nodes):
        for c in n.get('children', []): parent[c] = i
    def world(i):
        m = trs(nodes[i])
        while i in parent:
            i = parent[i]; m = mat_mul(trs(nodes[i]), m)
        return m
    lo = [1e30]*3; hi = [-1e30]*3
    for i, n in enumerate(nodes):
        if 'mesh' not in n: continue
        m = world(i)
        for prim in j['meshes'][n['mesh']]['primitives']:
            a = j['accessors'][prim['attributes']['POSITION']]
            if 'min' not in a: continue
            for cx, cy, cz in itertools.product(*[(a['min'][k], a['max'][k]) for k in range(3)]):
                p = [m[0]*cx+m[4]*cy+m[8]*cz+m[12], m[1]*cx+m[5]*cy+m[9]*cz+m[13], m[2]*cx+m[6]*cy+m[10]*cz+m[14]]
                for k in range(3): lo[k] = min(lo[k], p[k]); hi[k] = max(hi[k], p[k])
    return [hi[k]-lo[k] for k in range(3)]

res = {}
for d in sorted(os.listdir(CH)):
    g = os.path.join(CH, d, d + '.glb')
    if not os.path.exists(g) or d.startswith(('tower_', 'chibi', 'tikiman', 'mask', 'carapace')): continue
    res[d] = [round(v, 6) for v in glb_bounds(g)]
for k, v in res.items(): print(k, v)
with open(OUT, 'w') as fo:
    fo.write('// GENERATED by tools/data/export_enemy_bounds.py (character GLBs) - do not edit.\n')
    fo.write('// Renderer.bounds.size of the "Character"-tagged enemy model (bind pose), as the browser computes it (CharacterLibrary.prepare);\n')
    fo.write('// the sim derives the collision Cylinder from it (GameCoreEnemy ctor, Cylinder.fromBounds): [sizeX, sizeY, sizeZ].\n')
    fo.write('export const ENEMY_MODEL_BOUNDS: Readonly<Record<string, readonly [number, number, number]>> = ' + json.dumps(res, indent=1) + ';\n')
