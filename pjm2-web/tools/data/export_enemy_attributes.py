#!/usr/bin/env python3
"""Export Q4.EnemyAttributesSettings (per-enemy strength/class damage+reaction tables)
from decomp/data/enemy_roster.json into src/data/enemyAttributes.generated.ts.
Tables are [unknown, Normal, Soft/Magic, Hard/Physic] indexed by the enum value.
Usage: python3 tools/data/export_enemy_attributes.py"""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
roster = json.load(open(os.path.join(ROOT, '..', 'decomp', 'data', 'enemy_roster.json')))
def tab(infos, key):
    rows = [None] * 4
    for i in infos:
        rows[i[key]] = [round(i['damageTime'], 9), round(i['reactionTime'], 9),
                        1 if i['weakEffect']['m_PathID'] != 0 else 0]
    return rows
out = ['// GENERATED by tools/data/export_enemy_attributes.py from decomp/data/enemy_roster.json (do not edit).',
       '// Q4.EnemyAttributesSettings per enemy prefab: [damageTime, reactionTime, hasWeakEffect] per enum value',
       '// (strength: 0 unknown,1 Normal,2 Soft,3 Hard; class: 0 unknown,1 Normal,2 Magic,3 Physic).',
       'export const ENEMY_ATTRIBUTES: Readonly<Record<string, { effectScale: number; strength: number[][]; cls: number[][] }>> = {']
for name in sorted(roster):
    a = roster[name]['attributes'][0]
    out.append(f"  {name}: {{ effectScale: {round(a['effectScale'], 6)}, strength: {json.dumps(tab(a['strengthDamageInfos'], 'strength'))}, cls: {json.dumps(tab(a['classDamageInfos'], 'classType'))} }},")
out.append('};')
# Balloon prefabs: 12 EnemyAttributesSettings records in enemies_EnemyAttributesSettings.json belong to no enemy body (identical
# tables, one per Q4.Balloon); the other 21 unmatched records are boss attack-point tables (not mapped: no prefab hierarchy export).
allrec = json.load(open(os.path.join(ROOT, '..', 'decomp', 'data', 'enemies_EnemyAttributesSettings.json')))
def key(a): return json.dumps([a['effectScale'], [(i['damageTime'], i['reactionTime']) for i in a['strengthDamageInfos']], [(i['damageTime'], i['reactionTime']) for i in a['classDamageInfos']]])
bodies = {key(roster[n]['attributes'][0]) for n in roster}
import collections
left = collections.Counter(key(a) for a in allrec if key(a) not in bodies)
balloon = [a for a in allrec if left[key(a)] == 12][0]
out.append('/** Q4.Balloon EnemyAttributesSettings (12 identical records): Normal strength x10, Hard x0.1, Normal/Magic class x0.05. */')
out.append(f"export const BALLOON_ATTRIBUTES = {{ effectScale: {round(balloon['effectScale'], 6)}, strength: {json.dumps(tab(balloon['strengthDamageInfos'], 'strength'))}, cls: {json.dumps(tab(balloon['classDamageInfos'], 'classType'))} }};\n")
open(os.path.join(ROOT, 'src/data/enemyAttributes.generated.ts'), 'w').write('\n'.join(out))
print('wrote', len(roster))
