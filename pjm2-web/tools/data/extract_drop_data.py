#!/usr/bin/env python3
"""extract_drop_data.py — per-source pickup-drop data (Q4.PickupMovement overrides + stage PickupManagers).

PixelJunk Monsters 2 (CUSA11967, Unity 5.6.5p1), the user's own decrypted PS4 copy. Read-only against game
assets; writes ONLY  src/data/dropData.generated.ts  (and prints a markdown summary to stdout).

What the original does (docs/ENEMY_DROPS_ANALYSIS.md):
  Q4.PickupManager.OnEnemyDestroyed @0x3E3E20 -> CreateCurrency(coin, enemy.coinValue, enemyGO.GetComponent<PickupMovement>())
  and CreateCurrency(gem, enemy.gemValue, same movement).  So the ONLY serialized per-enemy drop datum is the
  Q4.PickupMovement component on each enemy logic prefab (launch force/cone/bounce/magnet).  Coin/gem AMOUNTS come
  from WaveResource (money/gem per wave, distributed by GameCoreWaveManager).  Player-bump drops use the
  tikiman_01 PickupMovement, gem-tower pops the tower prefab's PickupMovement (tower_005 only).

Run (from pjm2-web/):  /srv/opencode/venv-unity/bin/python -I tools/data/extract_drop_data.py
"""
import json
import os

import UnityPy

HERE = os.path.dirname(os.path.abspath(__file__))
PJ = os.path.abspath(os.path.join(HERE, '..', '..'))
REPO = os.path.abspath(os.path.join(PJ, '..'))
AB = os.path.join(REPO, 'game/extracted/CUSA11967/Media/StreamingAssets/AssetBundles')
OUT = os.path.join(PJ, 'src', 'data', 'dropData.generated.ts')

MOVE_KEYS = ['acceleration', 'rotateSpeed', 'rotateSpeedVariation', 'appearForceMin', 'appearForceMax',
             'appearRangeAngle', 'bouncingRate', 'bounceTime', 'attractOffset']


def load(bundle):
    env = UnityPy.load(os.path.join(AB, bundle))
    return env


def class_of(o, scripts):
    try:
        return scripts.get(o.read_typetree()['m_Script']['m_PathID'])
    except Exception:
        return None


def movement_by_go(bundle):
    env = load(bundle)
    idx = {o.path_id: o for o in env.objects}
    scripts = {}
    for o in env.objects:
        if o.type.name == 'MonoScript':
            try:
                scripts[o.path_id] = o.read().m_ClassName
            except Exception:
                pass
    out = {}
    for o in env.objects:
        if o.type.name != 'MonoBehaviour':
            continue
        try:
            t = o.read_typetree()
        except Exception:
            continue
        if scripts.get(t['m_Script']['m_PathID']) != 'PickupMovement':
            continue
        go = idx[t['m_GameObject']['m_PathID']].read().m_Name
        out[go] = {k: t[k] for k in MOVE_KEYS}
        out[go]['__path_id'] = o.path_id
    return out


def stage_pickup_managers():
    env = load('stages')
    res = {}
    for o in env.objects:
        if o.type.name != 'MonoBehaviour':
            continue
        try:
            t = o.read_typetree()
        except Exception:
            continue
        if 'globalCoinPerValueOverride' not in t:
            continue
        res[o.assets_file.name] = {
            'globalCoinPerValueOverride': t['globalCoinPerValueOverride'],
            'maximumFruitsOnGround': t['maximumFruitsOnGround'],
            'hiddenPickupData': [{'type': h['type'], 'amount': h['amount'], 'amountFruit': h['amountFruit']}
                                 for h in t['hiddenPickupData']],
            'hiddenFruitData': len(t['hiddenFruitData']),
        }
    return res


def f32(x):
    import struct
    return struct.unpack('<f', struct.pack('<f', x))[0]


def ts_move(m):
    ao = m['attractOffset']
    return ('{ acceleration: %r, rotateSpeed: %r, rotateSpeedVariation: %r, appearForceMin: %r, appearForceMax: %r, '
            'appearRangeAngle: %r, bouncingRate: %r, bounceTime: %d, attractOffset: { x: %r, y: %r, z: %r } }' % (
                m['acceleration'], m['rotateSpeed'], m['rotateSpeedVariation'], m['appearForceMin'],
                m['appearForceMax'], m['appearRangeAngle'], m['bouncingRate'], m['bounceTime'],
                ao['x'], ao['y'], ao['z']))


def main():
    enemies = movement_by_go('enemies')
    towers = movement_by_go('structures')
    player = movement_by_go('globalsettings')
    stages = stage_pickup_managers()
    assert len(enemies) == 57, len(enemies)

    L = []
    L.append('// src/data/dropData.generated.ts')
    L.append('// GENERATED by tools/data/extract_drop_data.py from the user\'s own CUSA11967 AssetBundles — do not edit.')
    L.append('// Serialized Q4.PickupMovement overrides + stage Q4.PickupManager records (see docs/ENEMY_DROPS_ANALYSIS.md).')
    L.append('')
    L.append("import type { PickupMovementContract } from '../view/q4-contracts';")
    L.append('')
    L.append('/** Serialized Q4.PickupMovement (rotateSpeed/Variation are view-only; the sim ignores them). */')
    L.append('export type PickupMovementRecord = PickupMovementContract & {')
    L.append('  rotateSpeed: number;')
    L.append('  rotateSpeedVariation: number;')
    L.append('};')
    L.append('')
    for name, table in (('ENEMY_PICKUP_MOVEMENT', enemies), ('TOWER_PICKUP_MOVEMENT', towers),
                        ('PLAYER_PICKUP_MOVEMENT', player)):
        doc = {'ENEMY_PICKUP_MOVEMENT': 'enemies bundle: PickupMovement on every one of the 57 enemy logic prefabs '
                                        '(Q4.PickupManager.OnEnemyDestroyed @0x3E3E20 passes it to CreateCurrency).',
               'TOWER_PICKUP_MOVEMENT': 'structures bundle: only tower_005 carries one (OnGemTowerBreak @0x3E41F0 / '
                                        'OnTowerSold use GetComponent<PickupMovement>; others fall back to the pickup prefab\'s).',
               'PLAYER_PICKUP_MOVEMENT': 'globalsettings bundle: tikiman_01 (Q4.PickupManager.OnPlayerBumped @0x3E4280).'}[name]
        L.append('/** %s */' % doc)
        L.append('export const %s: Readonly<Record<string, PickupMovementRecord>> = {' % name)
        for k in sorted(table):
            L.append('  %s: %s,' % (json.dumps(k), ts_move(table[k])))
        L.append('};')
        L.append('')
    L.append('/** Stage scene Q4.PickupManager serialized data (key = scene file, e.g. BuildPlayer-3d_stage_001_env). */')
    L.append('export interface StagePickupManagerRecord {')
    L.append('  globalCoinPerValueOverride: number; // 0 = unset (CreateCurrency falls back to the coin prefab value 20)')
    L.append('  maximumFruitsOnGround: number;')
    L.append('  hiddenPickupData: Array<{ type: number; amount: number; amountFruit: number }>;')
    L.append('  hiddenFruitDataCount: number;')
    L.append('}')
    L.append('export const STAGE_PICKUP_MANAGERS: Readonly<Record<string, StagePickupManagerRecord>> = {')
    for k in sorted(stages):
        s = stages[k]
        L.append('  %s: { globalCoinPerValueOverride: %d, maximumFruitsOnGround: %d, hiddenPickupData: %s, hiddenFruitDataCount: %d },'
                 % (json.dumps(k), s['globalCoinPerValueOverride'], s['maximumFruitsOnGround'],
                    json.dumps(s['hiddenPickupData']).replace('"type"', 'type').replace('"amountFruit"', 'amountFruit').replace('"amount"', 'amount'),
                    s['hiddenFruitData']))
    L.append('};')
    L.append('')
    with open(OUT, 'w') as fh:
        fh.write('\n'.join(L))
    print('wrote', OUT)

    # ---- markdown summary -------------------------------------------------
    print('\n### enemy PickupMovement (57)')
    groups = {}
    for k, m in enemies.items():
        key = (m['acceleration'], round(m['appearForceMin'], 3), round(m['appearForceMax'], 3), round(m['appearRangeAngle'], 3),
               round(m['bouncingRate'], 3), m['bounceTime'])
        groups.setdefault(key, []).append(k)
    for key, names in sorted(groups.items()):
        print(key, len(names), ', '.join(sorted(names)))
    print('\n### stages')
    for k in sorted(stages):
        print(k, stages[k])


if __name__ == '__main__':
    main()
