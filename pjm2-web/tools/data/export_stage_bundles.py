#!/usr/bin/env python3
"""export_stage_bundles.py -- emit one browser data bundle per stage + stages-index.json.

Generalises the (inline-generated) stage-1 slice public/assets/data/stage1-bundle.json.
Source tables: decomp/data/{stages_WaveResource,stage_waves_resolved,stages_StageMain}.json,
joined BY SOURCE SCENE via decomp/data/stage_scene_attribution.json (path_id join; the lists are
index-aligned but `tl_stage_00N` is NOT unique -- one per area -- so scene name is the key).

Each stage bundle has the exact shape src/data/waveResource.ts consumes (record at index 0):
  stages_WaveResource.json / stage_waves_resolved.json / stages_StageMain.json (1 record each)
  structures_TowerBase.json (tower_001 slice) + enemies_EnemyBase.json (57)  -- copied from the
  stage-1 bundle so every stage is self-contained (gzip makes the duplication cheap).
Stage 1 is NOT rewritten (its bundle is the byte-for-byte baseline); this script verifies that the
join reproduces it (--verify, default on) and writes stages 2..15 + public/assets/data/stages-index.json.

Usage: python3 tools/data/export_stage_bundles.py [--force-stage1]
"""
import json, os, sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
D = os.path.join(REPO, 'decomp/data')
OUT = os.path.join(REPO, 'pjm2-web/public/assets/data')
ld = lambda f: json.load(open(os.path.join(D, f)))

attr = ld('stage_scene_attribution.json')
wr = ld('stages_WaveResource.json'); sm = ld('stages_StageMain.json'); rs = ld('stage_waves_resolved.json')
areas = ld('globalsettings_AreaStageInfoMap.json')[0]['areaInfos']
base = json.load(open(os.path.join(OUT, 'stage1-bundle.json')))
info = {}  # scene -> area/stage info
for ai, a in enumerate(areas):
    for si, s in enumerate(a['stageInfos']):
        info[s['stageSceneName']] = dict(areaIndex=ai, stageIndexInArea=si, areaLabel=a['areaLabel'],
            stageLabel=s['stageLabel'], initialLocked=s['initialLocked'], unlocks=s['stageUnlockName'] or None,
            areaIDOverride=s['areaIDOverride'])
index = []
n = 0
for a in attr:
    scene = a['scene']
    if not scene.startswith('3d_stage_0') and not scene.startswith('3d_stage_1'):
        continue  # BuildPlayer-3d_stage_jovian_env = dev config, not in the AreaStageInfoMap
    n += 1
    wi = next(i for i, x in enumerate(wr) if x['__path_id'] == a['waveResource_pid'])
    mi = next(i for i, x in enumerate(sm) if x['__path_id'] == a['stageMain_pid'])
    assert wi == mi == rs[wi]['index'], (scene, wi, mi)
    assert rs[wi]['stageName'] == a['stageName'] and rs[wi]['areaName'] == a['areaName']
    b = {'_comment': f"Stage {n} ({scene}) slice of the user-owned extracted tables. Arrays hold the stage's record at index 0 "
                     f"(source index {wi} -- path_id-joined {a['waveResource_pid']}/{a['stageMain_pid']}). Generated by tools/data/export_stage_bundles.py.",
         'stages_WaveResource.json': [wr[wi]], 'stage_waves_resolved.json': [rs[wi]], 'stages_StageMain.json': [sm[mi]],
         'structures_TowerBase.json': base['structures_TowerBase.json'], 'enemies_EnemyBase.json': base['enemies_EnemyBase.json']}
    fn = f'stage{n}-bundle.json'
    if n == 1:
        # verify join reproduces the committed baseline
        assert base['stages_WaveResource.json'][0] == wr[wi] and base['stages_StageMain.json'][0] == sm[mi]
        assert base['stage_waves_resolved.json'][0] == rs[wi]
        if '--force-stage1' in sys.argv:
            json.dump(b, open(os.path.join(OUT, fn), 'w'))
    else:
        json.dump(b, open(os.path.join(OUT, fn), 'w'), separators=(',', ':'))
    waves = rs[wi]['waves']
    index.append(dict(stage=n, scene=scene, bundle=fn, bundleIdx=0, sourceIdx=wi, stageName=a['stageName'], areaName=a['areaName'],
                      initCoin=sm[mi]['m_initCoin'], initGem=sm[mi]['m_initGem'], waveCount=a['waveCount'],
                      initWaveTimeRate=sm[mi]['m_initWaveTimeRate'], initWaveCoinRate=sm[mi]['m_initWaveCoinRate'],
                      stageMusic=sm[mi]['m_stageMusic'], bossMusic=sm[mi]['m_bossMusic'], **info[scene]))
json.dump({'_comment': 'Per-stage index (stage number = AreaStageInfoMap order, 1..15). Generated by tools/data/export_stage_bundles.py.',
           'stages': index}, open(os.path.join(OUT, 'stages-index.json'), 'w'), indent=1)

# static TS catalogue (sync access in the browser + headless; no fetch on the stage-1 critical path)
rows = []
for e in index:
    rows.append("  { stage: %d, scene: '%s', bundle: '%s', stageName: '%s', areaName: '%s', areaIndex: %d, stageIndexInArea: %d, "
                "initCoin: %d, waveCount: %d, initialLocked: %s, unlocks: %s, areaIDOverride: %d }," % (
        e['stage'], e['scene'], e['bundle'], e['stageName'], e['areaName'], e['areaIndex'], e['stageIndexInArea'],
        e['initCoin'], e['waveCount'], 'true' if e['initialLocked'] else 'false',
        ("'%s'" % e['unlocks']) if e['unlocks'] else 'null', e['areaIDOverride']))
ts = os.path.join(REPO, 'pjm2-web/src/data/stageCatalog.generated.ts')
open(ts, 'w').write('''// GENERATED by tools/data/export_stage_bundles.py -- do not edit.
// Source: decomp/data/globalsettings_AreaStageInfoMap.json (+ stage_scene_attribution.json, stages_StageMain.json).
import type { StageCatalogEntry } from './stageCatalog';

export const STAGE_CATALOG: readonly StageCatalogEntry[] = [
%s
];
''' % '\n'.join(rows))
print('wrote', n, 'stages')
