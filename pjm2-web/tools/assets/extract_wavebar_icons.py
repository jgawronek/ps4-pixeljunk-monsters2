#!/usr/bin/env python3
"""
extract_wavebar_icons.py — per-enemy wave-bar icons (Q4.EnemyBase.m_waveBarSprite, 0x198).

Q4.WaveBarMonsterIcon.Init @0x9006B0 shows, for wave N, the m_waveBarSprite of GameCoreWaveManager.GetEnemyPrefabForWave(N)
(first spawner's enemy) on ImageZako / ImageBalloonZako / ImageBoss; Animator bools WithBalloon (EnemyBase.spawnMode == 2)
and IsBoss select the variant. Source: `enemies` AssetBundle (EnemyBase MonoBehaviours + their Sprite assets).

OUTPUT: public/assets/ui/sprites/wavebar_<sprite>.png (+ entries in public/assets/ui/sprites.json),
        src/data/enemyWaveBar.generated.ts  { <enemy logic prefab name>: {sprite, balloon, boss} }
Usage (from pjm2-web/): /srv/opencode/venv-unity/bin/python -I tools/assets/extract_wavebar_icons.py
"""
import json
import os
import UnityPy

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
AB = os.path.join(ROOT, '..', 'game/extracted/CUSA11967/Media/StreamingAssets/AssetBundles')
UI = os.path.join(ROOT, 'public', 'assets', 'ui')


def main():
    env = UnityPy.load(os.path.join(AB, 'enemies'))
    objs = {o.path_id: o for o in env.objects}
    sprites_json_path = os.path.join(UI, 'sprites.json')
    meta = json.load(open(sprites_json_path))
    rows = {}
    done = {}
    for pid, o in objs.items():
        if o.type.name != 'MonoBehaviour':
            continue
        try:
            t = o.read_typetree()
        except Exception:
            continue
        if 'm_waveBarSprite' not in t:
            continue
        go = objs[t['m_GameObject']['m_PathID']].read_typetree()['m_Name']
        sp = t['m_waveBarSprite']['m_PathID']
        if sp == 0 or sp not in objs:
            continue
        d = objs[sp].read()
        name = 'wavebar_' + d.m_Name
        if name not in done:
            img = d.image
            img.save(os.path.join(UI, 'sprites', name + '.png'))
            meta[name] = {'w': img.size[0], 'h': img.size[1], 'ppu': d.m_PixelsToUnits,
                          'pivot': [d.m_Pivot.x, d.m_Pivot.y], 'border': [0.0, 0.0, 0.0, 0.0]}
            done[name] = True
        rows[go] = {'sprite': name, 'balloon': t.get('spawnMode') == 2, 'boss': go.startswith('boss')}
    json.dump(meta, open(sprites_json_path, 'w'), indent=1, sort_keys=True)
    out = os.path.join(ROOT, 'src', 'data', 'enemyWaveBar.generated.ts')
    with open(out, 'w') as fh:
        fh.write('// GENERATED by tools/assets/extract_wavebar_icons.py — DO NOT EDIT.\n')
        fh.write('// Q4.EnemyBase.m_waveBarSprite (+ spawnMode==2 => WithBalloon) per enemy logic prefab.\n')
        fh.write('export interface WaveBarIconDef { sprite: string; balloon: boolean; boss: boolean }\n')
        fh.write('export const ENEMY_WAVE_BAR: Readonly<Record<string, WaveBarIconDef>> = ' + json.dumps(rows, indent=1, sort_keys=True) + ';\n')
    print('wrote', len(rows), 'enemies,', len(done), 'sprites')


if __name__ == '__main__':
    main()
