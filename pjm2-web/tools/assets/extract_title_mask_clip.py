#!/usr/bin/env python3
"""
extract_title_mask_clip.py — the `LogoMonster` AnimationClip (60.2 s loop) of the title screen: it animates ONLY
title_m2_mask (the white mask beside the "O"): RectTransform anchoredPosition x/y, localEuler z, localScale x/y.
Clip data: sharedassets3.assets (title_screen_01 prefab in level3). Decoded with extract_character.decode_clip
(StreamedClip/ConstantClip -> per-channel keyframes). RESTING x = 447 (the prefab's static 410 is overridden at t=0).
Output: src/view/ui/titleMaskClip.generated.ts
Usage (from pjm2-web/): /srv/opencode/venv-unity/bin/python -I tools/assets/extract_title_mask_clip.py
"""
import json
import os
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, 'pylibs'))
import UnityPy  # noqa: E402
import extract_character as ec  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
MEDIA = os.path.join(ROOT, '..', 'game/extracted/CUSA11967/Media')
OUT = os.path.join(ROOT, 'src', 'view', 'ui', 'titleMaskClip.generated.ts')


def main():
    os.chdir(MEDIA)
    env = UnityPy.load('level3', 'sharedassets3.assets', 'globalgamemanagers.assets', 'sharedassets0.assets')
    sa = env.files['sharedassets3.assets']
    clip = [o for o in sa.objects.values() if o.type.name == 'AnimationClip' and o.read().m_Name == 'LogoMonster'][0]
    lv = env.files['level3']
    objs = lv.objects
    paths = []

    def walk(tp, prefix):
        t = objs[tp].read_typetree()
        g = objs[t['m_GameObject']['m_PathID']].read_typetree()
        p = (prefix + '/' + g['m_Name']).lstrip('/')
        paths.append(p)
        for c in t['m_Children']:
            walk(c['m_PathID'], p)

    for o in objs.values():
        if o.type.name in ('Transform', 'RectTransform'):
            t = o.read_typetree()
            if t['m_Father']['m_PathID'] == 0 and objs[t['m_GameObject']['m_PathID']].read_typetree()['m_Name'] == 'title_screen_01':
                walk(o.path_id, '')
    crc = {}
    for p in paths:
        parts = p.split('/')
        for i in range(len(parts)):
            s = '/'.join(parts[i:])
            crc[zlib.crc32(s.encode())] = s
    out = ec.decode_clip(None, clip, crc, None)
    tracks = {}
    names = {'localEulerAnglesRaw.z': 'rotZ', 'm_LocalScale.x': 'scaleX', 'm_LocalScale.y': 'scaleY'}
    for b in out['bindings']:
        # RectTransform channels (typeID 224) carry no path in the decoded clip; every binding of this clip targets the mask
        if not (b['path'].endswith('title_m2_mask') or b['property'].startswith('type224')):
            continue
        k = names.get(b['property'])
        if k is None and b['property'] == 'type224attr[%d]' % zlib.crc32(b'm_AnchoredPosition.x'):
            k = 'x'
        if k is None and b['property'] == 'type224attr[%d]' % zlib.crc32(b'm_AnchoredPosition.y'):
            k = 'y'
        if k is not None:
            tracks[k] = [[round(t, 4), round(v, 4)] for t, v in zip(b['times'], b['values'])]
    data = {'length': round(out['stopTime'], 3), 'loop': bool(out['loopTime']), 'tracks': tracks}
    with open(OUT, 'w') as fh:
        fh.write('// GENERATED by tools/assets/extract_title_mask_clip.py — DO NOT EDIT.\n')
        fh.write('// Title screen LogoMonster clip (sharedassets3): the white mask next to the "O". Tracks are [time, value] keys.\n')
        fh.write('// x/y = RectTransform.anchoredPosition (canvas px, relative to the logo top-left, pivot (1, 0.5)); rotZ degrees; scale.\n')
        fh.write('export const TITLE_MASK_CLIP = ' + json.dumps(data) + ' as const;\n')
    print('wrote', OUT, {k: len(v) for k, v in tracks.items()}, data['length'])


if __name__ == '__main__':
    main()
