#!/usr/bin/env python3
"""
extract_title_clips.py — the title screen Animator clips (sharedassets3: InStart, StartIdle, StartOut, In, Out, OutStart, ...) decoded with
exact per-key cubic coefficients and resolved node paths (title_screen_01 hierarchy). The generic decoder (extract_character.decode_clip)
drops the path of RectTransform / MonoBehaviour channels and keeps only key values; here every channel keeps (time, c0, c1, c2, c3)
so the web port evaluates v(dt) = ((c0*dt + c1)*dt + c2)*dt + c3 on the segment starting at that key — Unity's own curve.

Output: src/view/ui/titleClips.generated.ts   { clip: { length, loop, nodes: { <node>: { <property>: [[t,c0,c1,c2,c3],...] } } } }
Usage (from pjm2-web/): /srv/opencode/venv-unity/bin/python -I tools/assets/extract_title_clips.py
"""
import json
import os
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, 'pylibs'))
import UnityPy  # noqa: E402
import extract_character as ec  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
MEDIA = os.path.join(ROOT, '..', 'game/extracted/CUSA11967/Media')
OUT = os.path.join(ROOT, 'src', 'view', 'ui', 'titleClips.generated.ts')

PROPS = ['m_AnchoredPosition.x', 'm_AnchoredPosition.y', 'm_SizeDelta.x', 'm_SizeDelta.y', 'm_Color.a', 'm_Color.r', 'm_Color.g',
         'm_Color.b', 'm_Alpha', 'm_LocalScale.x', 'm_LocalScale.y', 'm_LocalScale.z', 'm_Pivot.x', 'm_Pivot.y', 'm_Enabled', 'm_IsActive']
EULER = {1: 'm_LocalPosition.', 2: 'm_LocalRotation.', 3: 'm_LocalScale.', 4: 'localEulerAnglesRaw.'}


def main():
    os.chdir(MEDIA)
    env = UnityPy.load('level3', 'sharedassets3.assets', 'globalgamemanagers.assets', 'sharedassets0.assets')
    sa = env.files['sharedassets3.assets']
    objs = env.files['level3'].objects
    paths = []

    def walk(tp, prefix):
        t = objs[tp].read_typetree()
        g = objs[t['m_GameObject']['m_PathID']].read_typetree()
        p = (prefix + '/' + g['m_Name']).lstrip('/')
        paths.append(p)
        for c in t['m_Children']:
            walk(c['m_PathID'], p)

    for o in objs.values():
        if o.type.name in ('Transform', 'RectTransform'):
            t = o.read_typetree()
            if t['m_Father']['m_PathID'] == 0 and objs[t['m_GameObject']['m_PathID']].read_typetree()['m_Name'] == 'title_screen_01':
                walk(o.path_id, '')
    crc = {}
    for p in paths:
        parts = p.split('/')
        for i in range(len(parts)):
            s = '/'.join(parts[i:])
            crc[zlib.crc32(s.encode())] = s
    prop_by_hash = {zlib.crc32(s.encode()): s for s in PROPS}

    clips = {}
    for o in sa.objects.values():
        if o.type.name != 'AnimationClip':
            continue
        ct = o.read_typetree()
        name = ct['m_Name']
        mc = ct.get('m_MuscleClip') or {}
        cd = ((mc.get('m_Clip') or {}).get('data')) or {}
        gb = ct['m_ClipBindingConstant']['genericBindings']
        layout, _ = ec.binding_layout(gb)
        sc = cd.get('m_StreamedClip') or {}
        dc = cd.get('m_DenseClip') or {}
        cc = cd.get('m_ConstantClip') or {}
        stream_count = sc.get('curveCount', 0)
        chans = {}
        for t, keys in ec.decode_streamed_frames(sc.get('data') or []):
            if t is None:
                continue
            for ci, coeff in keys:
                chans.setdefault(ci, []).append([round(t, 4)] + [round(c, 6) for c in coeff])
        # constant channels: a single key
        for k, v in enumerate(cc.get('data') or []):
            chans[stream_count + (dc.get('m_CurveCount', 0)) + k] = [[0.0, 0.0, 0.0, 0.0, round(v, 6)]]
        nodes = {}
        for ci, keys in sorted(chans.items()):
            bnd, comp = ec.find_binding(layout, ci)
            if bnd is None:
                continue
            path = '' if bnd['path'] == 0 else crc.get(bnd['path'], 'UNKNOWN_%d' % bnd['path'])
            node = path.split('/')[-1] if path else '(root)'
            if bnd['typeID'] == 4:
                base = EULER.get(bnd['attribute'])
                prop = (base + 'xyzw'[comp]) if base else 'attr%s' % bnd['attribute']
            else:
                prop = prop_by_hash.get(bnd['attribute'], 'attr%s' % bnd['attribute'])
            nodes.setdefault(node, {})[prop] = keys
        clips[name] = {'length': round(mc.get('m_StopTime', 0) - mc.get('m_StartTime', 0), 4), 'loop': bool(mc.get('m_LoopTime')), 'nodes': nodes}
    with open(OUT, 'w') as fh:
        fh.write('// GENERATED by tools/assets/extract_title_clips.py — DO NOT EDIT.\n')
        fh.write('// Title screen Animator clips (sharedassets3). Keys: [time, c0, c1, c2, c3]; v(dt) = ((c0*dt + c1)*dt + c2)*dt + c3 on the segment from that key.\n')
        fh.write('// RectTransform values are canvas px relative to the node anchor (anchored TL: y negative = below the top edge).\n')
        fh.write('export const TITLE_CLIPS: Readonly<Record<string, { length: number; loop: boolean; nodes: Record<string, Record<string, number[][]>> }>> = '
                 + json.dumps(clips) + ';\n')
    print('wrote', OUT, {k: (v['length'], list(v['nodes'])) for k, v in clips.items() if k in ('InStart', 'StartIdle', 'StartOut')})


if __name__ == '__main__':
    main()
