#!/usr/bin/env python3
"""
extract_loading_screen.py — the ORIGINAL loading screen (prefab `LoadingMenu` in the `loading_ui` bundle + Q4.LoadingTipsMap in
`globalsettings`) -> web data. See docs/LOADING_SCREEN_ANALYSIS.md.

Outputs
  public/assets/ui/loading/loading_bg_NNN.webp   the 25 background atlases (2048x1024; parts: centre 1920x1024 @0,0, bottom-left
                                                 56x1024 @1927,0, bottom-right 56x896 @1992,128; the two strips are drawn rotated 90 deg
                                                 CCW under the main image by the prefab: Image_part02/03 localRotation z=0.7071,w=0.7071)
  public/assets/ui/loading/scroll_up.png / scroll_down.png   shop_sign_up / shop_sign_down (158x90, common_img_00) scroll arrows
  src/view/loading/loadingScreen.generated.ts    tips (42 LoadingTip rows), background list, LoadingScreen serialized timings
Binary-derived images live under the gitignored public/assets/.
Usage (from pjm2-web/): /srv/opencode/venv-unity/bin/python -I tools/assets/extract_loading_screen.py
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, 'pylibs'))
import UnityPy  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
BASE = os.path.join(ROOT, '..', 'game/extracted/CUSA11967/Media/StreamingAssets/AssetBundles')
OUT_IMG = os.path.join(ROOT, 'public', 'assets', 'ui', 'loading')
OUT_TS = os.path.join(ROOT, 'src', 'view', 'loading', 'loadingScreen.generated.ts')


def main():
    os.makedirs(OUT_IMG, exist_ok=True)
    os.makedirs(os.path.dirname(OUT_TS), exist_ok=True)
    gs = UnityPy.load(os.path.join(BASE, 'globalsettings'))
    lu = UnityPy.load(os.path.join(BASE, 'loading_ui'))
    names = {}
    for env in (gs, lu):
        for o in env.objects:
            if o.type.name in ('Texture2D', 'Sprite'):
                names[(id(env), o.path_id)] = o.read().m_Name
    gnm = {pid: n for (e, pid), n in names.items() if e == id(gs)}
    tips = None
    lscreen = None
    for o in gs.objects:
        if o.type.name == 'MonoBehaviour':
            t = o.read_typetree()
            if t.get('m_Name') == 'LoadingTipsMap':
                tips = t
    for o in lu.objects:
        if o.type.name == 'MonoBehaviour':
            t = o.read_typetree()
            if 'minTipDisplayTime' in t:
                lscreen = t
    assert tips is not None and lscreen is not None
    rows = []
    for s in tips['tipSettings']:
        rows.append({'atlas': gnm.get(s['atlas']['m_PathID']), 'tip': s['tip'], 'title': s['title'],
                     'unlockStages': s['unlockStages'], 'unlockItems': s['unlockItems'],
                     'requiredDLC': s['requiredDLC'], 'requiresNetworking': bool(s['requiresNetworking'])})
    # backgrounds: texture names of the 25 sets + dump the textures
    bgs = []
    seen = set()
    for env in (gs, lu):
        for o in env.objects:
            if o.type.name == 'Texture2D':
                d = o.read()
                if d.m_Name.startswith('loading_bg_') and d.m_Name not in seen:
                    seen.add(d.m_Name)
                    d.image.save(os.path.join(OUT_IMG, d.m_Name + '.webp'), 'WEBP', quality=88, method=4)
                    bgs.append(d.m_Name)
    bgs.sort()
    for o in lu.objects:
        if o.type.name == 'Sprite':
            d = o.read()
            if d.m_Name in ('shop_sign_up', 'shop_sign_down'):
                d.image.save(os.path.join(OUT_IMG, 'scroll_' + d.m_Name.split('_')[-1] + '.png'))
    ls = {k: lscreen[k] for k in ('scrollSpeed', 'defaultScrollViewPos', 'loadingTipsEnable', 'minTipDisplayTime', 'maxTipDisplayTime',
                                  'backgroundFadeSpeed', 'backgroundScaleSpeedMax')}
    with open(OUT_TS, 'w') as fh:
        fh.write('// GENERATED by tools/assets/extract_loading_screen.py — DO NOT EDIT. Source: globalsettings LoadingTipsMap + loading_ui LoadingMenu.\n')
        fh.write('export interface LoadingTipRow { atlas: string; tip: string; title: string; unlockStages: string[]; unlockItems: string[]; '
                 'requiredDLC: number; requiresNetworking: boolean }\n')
        fh.write('export const LOADING_TIPS: readonly LoadingTipRow[] = ' + json.dumps(rows) + ';\n')
        fh.write('export const LOADING_BACKGROUNDS: readonly string[] = ' + json.dumps(bgs) + ';\n')
        fh.write('export const LOADING_SCREEN_SETTINGS = ' + json.dumps(ls) + ' as const;\n')
    print('tips', len(rows), 'bgs', len(bgs), ls)


if __name__ == '__main__':
    main()
