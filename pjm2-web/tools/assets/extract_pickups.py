def mesh_bounds(b, mesh_pid):
    """Vertex min/max/size in glTF (mirrored) space; size is mirror-invariant
    and matches the serialized m_LocalAABB to float32 rounding."""
    mesh = b.idx[mesh_pid].read()
    h = MeshHandler(mesh)
    h.process()
    pos = np.nan_to_num(np.array(h.m_Vertices, dtype=np.float32))
    pos[:, 0] *= -1
    mn, mx = pos.min(axis=0), pos.max(axis=0)
    return {'min': mn.tolist(), 'max': mx.tolist(),
            'size': (mx - mn).tolist(), 'center': ((mx + mn) / 2).tolist(),
            'vertexCount': int(h.m_VertexCount)}


def find_clips(b, visual_name):
    """Any AnimationClip in the bundle name-matched to the visual prefab.
    (Expected EMPTY: spin is code-driven, Animator controller is null.)"""
    prefix = visual_name.split('_')[0]
    found = []
    for o in b.env.objects:
        if o.type.name != 'AnimationClip':
            continue
        try:
            n = o.read().m_Name
        except Exception:
            continue
        if n.startswith(prefix + '_') or n.startswith(prefix + '@') or n == prefix:
            found.append({'name': n, 'pathId': o.path_id, 'assetsFile': o.assets_file.name})
    return found


def process_pickup(p, b, texstore):
    name = p['visualPrefab']['name'].replace('_pa', '')  # coin_001 / gem_001
    t0 = time.time()
    work_dir = os.path.join(WORK, name)
    os.makedirs(work_dir, exist_ok=True)
    glb_path = os.path.join(OUT, f'{name}.glb')

    # ---- logic prefab: PickupCurrency component pid from decomp data ----
    comp_pid = p['__path_id']
    r = b.idx.get(comp_pid)
    if r is None or r.type.name != 'MonoBehaviour':
        raise RuntimeError(f'{name}: PickupCurrency component pid {comp_pid} not in props bundle')
    tt = r.read_typetree()
    logic_pid = ec.ref_pid(tt.get('m_GameObject'))
    logic_name = b.name_of(logic_pid)
    if logic_name != p['__gameObject']:
        raise RuntimeError(f'{name}: logic GO name {logic_name} != expected {p["__gameObject"]}')

    # ---- visual prefab via PrefabLoader.prefabList[0] (cross-check decomp) ----
    visual_pid = logic_pid
    for c in b.tt(logic_pid)['m_Component']:
        cpid = ec.ref_pid(c['component'])
        if b.idx[cpid].type.name == 'MonoBehaviour' and b.comp_class(b.idx[cpid]) == 'PrefabLoader':
            pl = b.tt(cpid).get('prefabList') or []
            if pl:
                visual_pid = ec.ref_pid(pl[0])
    if visual_pid != p['visualPrefab']['path_id']:
        raise RuntimeError(f'{name}: PrefabLoader visual {visual_pid} != decomp {p["visualPrefab"]["path_id"]}')
    visual_name = b.name_of(visual_pid)

    logic_inv = ec.component_inventory(b, logic_pid, 'logic')
    visual_inv = ec.component_inventory(b, visual_pid, 'visual')
    with open(os.path.join(work_dir, 'components.json'), 'w') as f:
        json.dump({'prefabName': logic_name, 'visualPrefab': visual_name,
                   'logicPrefab': logic_inv, 'visualPrefabInv': visual_inv,
                   'visualResolvedVia': 'PrefabLoader.prefabList[0]'}, f, indent=1, default=str)
    visual_nodes = visual_inv['nodes']

    # ---- LOD0 static MeshFilter + MeshRenderer only ----
    renderers = []
    for n in visual_nodes:
        if 'LOD0' not in n['name']:
            continue
        mf = next((c for c in n['components'] if c['type'] == 'MeshFilter'), None)
        mr = next((c for c in n['components'] if c['type'] == 'MeshRenderer'), None)
        if mf and mr:
            renderers.append({'kind': 'static', 'pid': mf['path_id'], 'node': n['name'],
                              'rendererPid': mr['path_id']})
    if not renderers:
        raise RuntimeError(f'{name}: no LOD0 MeshFilter+MeshRenderer in {visual_name}')
    mat_pids = []
    for rd in renderers:
        for m in b.tt(rd['rendererPid']).get('m_Materials', []):
            mp = ec.ref_pid(m)
            if mp and mp not in mat_pids:
                mat_pids.append(mp)

    # ---- GLB (mirror baked in, same as characters) ----
    w = eac.WebWriter()
    mat_index = build_pickup_materials(b, 'props', mat_pids, texstore, w)
    glb_stats, _ = eac.export_character_glb(
        b, 'props', visual_nodes, renderers, mat_index, w,
        generator='pjm2-web extract_pickups.py (UnityPy + hand-rolled glTF)')
    data, _j = w.finish([0], generator='pjm2-web extract_pickups.py')
    with open(glb_path, 'wb') as f:
        f.write(data)

    # ---- clips (expected none) + bounds ----
    clips = find_clips(b, visual_name)
    mesh_pid = ec.ref_pid(b.tt(renderers[0]['pid']).get('m_Mesh'))
    bounds = mesh_bounds(b, mesh_pid)

    # ---- validate (trimesh reload; one geometry per primitive) ----
    trimesh_verts = sum(m['vertices'] * m['submeshes'] for m in glb_stats['meshes'])
    verrs, vinfo = eac.validate_glb(glb_path, {'clips': len(clips), 'vertices': trimesh_verts})

    # ---- textures used by this pickup ----
    tex_recs = []
    seen = set()
    for mp in mat_pids:
        for te in b.tt(mp).get('m_SavedProperties', {}).get('m_TexEnvs', []):
            tpid = ec.ref_pid(te[1].get('m_Texture'))
            if tpid and ('props', tpid) in texstore.recs and tpid not in seen:
                seen.add(tpid)
                r2 = texstore.recs[('props', tpid)]
                tex_recs.append({k: r2[k] for k in ('textureName', 'pathId', 'file', 'webpFile',
                                                    'colorSpace', 'sourceColorSpace',
                                                    'convertedLinearToSrgb', 'width', 'height',
                                                    'pngBytes', 'webpBytes', 'sourceFormat',
                                                    'sourceFormatName', 'meanRGBA', 'note', 'error')
                                 if k in r2} | {'slots': sorted({u['slot'] for u in r2['usedBy']})})

    entry = {
        'name': name,
        'role': p['role'],
        'file': f'{name}.glb',
        'glbBytes': os.path.getsize(glb_path),
        'glbSha256': sha256(glb_path),
        'textures': tex_recs,
        'clips': clips,
        'bounds': bounds,
        'vertexCount': sum(m['vertices'] for m in glb_stats['meshes']),
        'triangleCount': sum(m['triangles'] for m in glb_stats['meshes']),
        'source': {
            'bundle': 'props',
            'sourceAsset': p['__source_asset'],
            'logicPrefab': logic_name,
            'visualPrefab': visual_name,
            'pathIds': {'pickupCurrencyComponent': comp_pid, 'logicGameObject': logic_pid,
                        'visualPrefab': visual_pid,
                        'meshes': [m['meshPathId'] for m in glb_stats['meshes']],
                        'materials': mat_pids},
            'assetsFile': b.idx[mesh_pid].assets_file.name,
        },
        # Code-driven view motion constants (decomp evidence — see PickupView.ts):
        'movement': {
            'rotateSpeed': p['pickupMovement']['rotateSpeed'],
            'rotateSpeedVariation': p['pickupMovement']['rotateSpeedVariation'],
            'initialYawRangeDeg': [0, 180],
            'evidence': 'Q4.PickupCurrency.Update @0x3E2A30 (Rotate(up*rotateSpeed*dt)); '
                        'Q4.PickupCurrency.Awake @0x3E2950 (Random.Range(0,180) yaw); '
                        'PickupMovement fields dump.cs TypeDefIndex 3146',
        },
        'pickup': p['pickup'],
        'pickupCurrency': p['pickupCurrency'],
        'pickupMovement': p['pickupMovement'],
        'pickupLifeCycle': p['pickupLifeCycle'],
        'glbWarnings': glb_stats['warnings'],
        'validation': {'errors': verrs, **vinfo},
        'extractSeconds': round(time.time() - t0, 2),
    }
    log(f'  {name} ({p["role"]}): {entry["vertexCount"]} verts / {entry["triangleCount"]} tris / '
        f'{len(tex_recs)} tex / {len(clips)} clips / {entry["glbBytes"]} bytes '
        f'{"VALID" if not verrs else "WARN:" + str(verrs)} [{time.time()-t0:.1f}s]')
    return entry


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--force', action='store_true', help='re-extract even if outputs exist')
    args = ap.parse_args()
    t_start = time.time()
    os.makedirs(OUT, exist_ok=True)
    log(f'extract_pickups.py START out={OUT}')

    data = json.load(open(PICKUP_DATA))
    b = ec.Bundle(os.path.join(BUNDLES, 'props'))
    log(f'props bundle: {len(b.idx)} objects')
    texstore = PickupTextureStore()

    old = {}
    old_manifest = os.path.join(OUT, 'manifest.json')
    if os.path.exists(old_manifest):
        try:
            old = {e['name']: e for e in json.load(open(old_manifest)).get('pickups', [])}
        except Exception:
            old = {}
    entries = []
    for p in data['prefabs']:
        name = p['visualPrefab']['name'].replace('_pa', '')
        if (not args.force and os.path.exists(os.path.join(OUT, f'{name}.glb')) and name in old):
            log(f'  {name}: exists, skipped (--force to re-extract)')
            entries.append(old[name])
            continue
        entries.append(process_pickup(p, b, texstore))
    texstore.write_sentinel()

    manifest = {
        'generatedUtc': time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime()),
        'generatedBy': 'pjm2-web/tools/assets/extract_pickups.py',
        'source': {'bundle': os.path.join(BUNDLES, 'props'),
                   'prefabData': os.path.relpath(PICKUP_DATA, ROOT),
                   'unityVersion': '.'.join(str(x) for x in (b.unity_version or ())[:3])},
        'coordinateConvention': 'glTF outputs mirrored Unity->glTF (X negated, winding/V flipped); '
                                'load in three native space, mirror sim positions x->-x only',
        'texturePolicy': 'baseColor (sRGB) + occlusion bound; bump/metallic-gloss manifest-only '
                         '(character pipeline policy). textures_webp/_ok sentinel enables the '
                         'loader PNG->WebP URL rewrite.',
        'animationPolicy': 'no clips: spin is code-driven (movement.rotateSpeed), initial yaw '
                           'random 0..180 deg in Awake; bounce/scatter is SIM physics '
                           '(GameCorePickup ctor), not view animation',
        'pickups': entries,
    }
    with open(os.path.join(OUT, 'manifest.json'), 'w') as f:
        json.dump(manifest, f, indent=1)
    log(f'manifest.json written ({len(entries)} pickups)')
    log(f'extract_pickups.py DONE in {time.time()-t_start:.1f}s')


if __name__ == '__main__':
    main()
