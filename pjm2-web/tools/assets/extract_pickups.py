#!/usr/bin/env python3
"""
extract_pickups.py — PixelJunk Monsters 2 (PS4) coin/gem pickup asset extractor.

Extracts the REAL currency pickup visuals from the user's own `props` bundle:
  coin: prop_001 (PickupCurrency pid 1569343402696278429)
        -> PrefabLoader -> coin_001_pa -> coin_001_comp_LOD0 (166 verts)
  gem:  prop_002 (PickupCurrency pid -7195634620545009480)
        -> PrefabLoader -> gem_001_pa  -> gem_001_comp_LOD0 (73 verts)
Prefab identities + path_ids cross-checked against decomp/data/pickup_prefabs.json
(generated by tools/data/extract_pickup_data.py from the same bundles).

Outputs (browser-ready, public/assets/pickups/):
  coin_001.glb / gem_001.glb   LOD0 static mesh + full transform hierarchy +
                               materials referencing shared PNGs
  textures/<tex>__<pid>.png    albedo sRGB-encoded when source is linear
                               (m_ColorSpace=1), data maps stay linear
  textures_webp/<...>.webp     WebP repack of every texture (+ `_ok` sentinel);
                               PickupView.load rewrites PNG URIs to these when
                               the sentinel is present (CharacterLibrary pattern)
  manifest.json                {name, file, textures, clips, bounds, ...} per pickup

Scratch (not shipped): pjm2-web/.work/pickups/<name>/components.json

NO animation clips exist for these prefabs (verified: zero AnimationClips in
the props bundle match coin*/gem*; the visual Animator has a null controller).
The coin/gem spin is CODE-DRIVEN in the original:
  Q4.PickupCurrency.Update @0x3E2A30:
    transform.Rotate(Vector3.up * m_pickupMovement.rotateSpeed * Time.deltaTime)
  PickupMovement.rotateSpeed = -180 deg/s on BOTH prefabs (variation 0)
  Q4.PickupCurrency.Awake @0x3E2950: random initial yaw Random.Range(0, 180)
manifest.movement records these constants for the view layer.

Pipeline reuse (established pattern — see extract_all_characters.py):
  imports extract_character as ec (Bundle/walk_tree/GltfWriter/mirror math)
  and extract_all_characters as eac (WebWriter/export_character_glb/
  validate_glb/srgb_encode), both unmodified.

COORDINATE CONVENTION (identical to the character pipeline):
  Unity LH Y-up -> glTF RH Y-up: mirror X on positions/normals/translations,
  quaternion (x,y,z,w) -> (x,-y,-z,w), winding (a,b,c) -> (a,c,b), UV v -> 1-v.
  GLBs load in three.js NATIVE space; the view mirrors sim POSITIONS only.

Usage:
  /srv/opencode/venv-unity/bin/python tools/assets/extract_pickups.py [--force]
"""
